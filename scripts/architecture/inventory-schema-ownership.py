#!/usr/bin/env python3
"""Generate a conservative SQL-table to migration/module-reference inventory.

This is lexical evidence, not a database catalog or a definitive ownership model:
SQL assembled dynamically, ORM metadata, aliases, views, and runtime behavior may
not be visible to this scan.
"""
from __future__ import annotations
import argparse
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MIGRATIONS = ROOT / "data" / "migrations" / "postgres"
GO_ROOT = ROOT / "services" / "api"
CREATE_RE = re.compile(r"^[ \t]*CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?(?:[\w\"]+\.)?([\w\"]+)", re.I | re.M)
ALTER_RE = re.compile(r"^[ \t]*ALTER\s+TABLE\s+(?:IF\s+EXISTS\s+)?(?:[\w\"]+\.)?([\w\"]+)", re.I | re.M)
SQL_USE_RE_TEMPLATE = r"\b(?:FROM|JOIN|INTO|UPDATE|TABLE|DELETE\s+FROM)\s+(?:ONLY\s+)?(?:[\w\"]+\.)?[\"]?{table}[\"]?\b"


def clean(identifier: str) -> str:
    return identifier.strip('"').lower()


def build_report() -> str:
    migrations: dict[str, set[str]] = defaultdict(set)
    for file in sorted(MIGRATIONS.glob("*.sql")):
        content = file.read_text(errors="replace")
        for regex in (CREATE_RE, ALTER_RE):
            for match in regex.finditer(content):
                migrations[clean(match.group(1))].add(file.name)

    modules: dict[str, set[str]] = defaultdict(set)
    for source in sorted(GO_ROOT.rglob("*.go")):
        try:
            content = source.read_text(errors="replace")
        except OSError:
            continue
        rel = source.relative_to(GO_ROOT)
        parts = rel.parts
        module = parts[2] if len(parts) > 2 and parts[0:2] == ("internal", "modules") else "composition/shared"
        for table in migrations:
            if re.search(SQL_USE_RE_TEMPLATE.format(table=re.escape(table)), content, re.I):
                modules[table].add(module)

    lines = [
        "# SQL Schema Ownership Inventory (Static Evidence)",
        "",
        "> Generated by `scripts/architecture/inventory-schema-ownership.py`. This is a conservative lexical inventory, not a definitive ownership decision. Validate each candidate against repositories, transaction flows, and a live PostgreSQL catalog before changing schema ownership.",
        "",
        f"Tables/objects seen in CREATE TABLE or ALTER TABLE statements: **{len(migrations)}**.",
        "",
        "| Table | Migration evidence | Go modules with SQL-like references | Assessment |",
        "|---|---|---|---|",
    ]
    for table in sorted(migrations):
        migs = ", ".join(sorted(migrations[table]))
        refs = sorted(modules.get(table, set()))
        refs_text = ", ".join(f"`{x}`" for x in refs) if refs else "No static reference found"
        if len(refs) == 1:
            assessment = "Single-module candidate; confirm write authority"
        elif len(refs) > 1:
            assessment = "Shared reference; investigate cross-domain ownership"
        else:
            assessment = "Unmapped; check SQL construction, external consumers, or dead schema"
        lines.append(f"| `{table}` | {migs} | {refs_text} | {assessment} |")
    # Surface important Logix SQL dependencies that have no migration evidence.
    # Keep this scoped to the product being restructured so generic SQL parsing
    # does not overstate CTE aliases, vendor catalog names, or query fragments.
    logix_refs: dict[str, set[str]] = defaultdict(set)
    logix_root = GO_ROOT / "internal" / "modules" / "logix"
    logix_ref_re = re.compile(r"\b(?:FROM|JOIN|INTO|UPDATE|DELETE\s+FROM)\s+(?:ONLY\s+)?(?:[\w\"]+\.)?[\"]?([a-zA-Z_][\w]*)[\"]?", re.I)
    for source in sorted(logix_root.rglob("*.go")):
        source_content = source.read_text(errors="replace")
        # Scan raw SQL literals only; ordinary Go prose and error messages can
        # contain words such as "update", "outbox", or "candidate".
        content = "\n".join(re.findall(r"`(.*?)`", source_content, flags=re.S))
        content = re.sub(r"/\*.*?\*/", " ", content, flags=re.S)
        content = re.sub(r"--[^\n]*", " ", content)
        for match in logix_ref_re.finditer(content):
            table = clean(match.group(1))
            if table not in {"information_schema", "pg_catalog", "set", "values", "unnest", "columns", "candidate", "skip"}:
                logix_refs[table].add(source.relative_to(ROOT).as_posix())

    unresolved_logix = {table: refs for table, refs in logix_refs.items() if table not in migrations}
    lines += [
        "",
        "## Logix SQL references without migration evidence",
        "",
        "This targeted check compares table-like identifiers referenced by Logix Go SQL with objects established by `data/migrations/postgres/*.sql`. It is lexical evidence only; confirm external schemas, views, ORM-managed objects, and deployment-provisioned tables before concluding an object does not exist.",
        "",
    ]
    if unresolved_logix:
        lines += ["| Referenced object | Go source evidence | Status |", "|---|---|---|"]
        for table in sorted(unresolved_logix):
            refs = ", ".join(f"`{ref}`" for ref in sorted(unresolved_logix[table]))
            lines.append(f"| `{table}` | {refs} | No matching CREATE/ALTER migration evidence |")
    else:
        lines.append("No unresolved Logix table references detected by this scan.")

    lines += [
        "",
        "## Interpretation rules",
        "",
        "- A module reference is detected only when a known table name appears after a common SQL verb (`FROM`, `JOIN`, `INTO`, `UPDATE`, `TABLE`, or `DELETE FROM`) in Go source. It may include comments or dead code and may miss dynamically assembled SQL.",
        "- Migration mentions include both `CREATE TABLE` and `ALTER TABLE`; the same table can therefore be associated with multiple migration files.",
        "- `single-module candidate` is not equivalent to approved ownership. Ownership must include all writers, readers, state transitions, constraints, event consumers, and recovery paths.",
        "- Do not rename or split tables based on this report alone. Treat `transactions`, `payouts`, ledger tables, and any multi-module reference as requiring an explicit data-owner decision.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, help="Write report to this path instead of stdout")
    args = parser.parse_args()
    report = build_report()
    if args.output:
        output = args.output if args.output.is_absolute() else ROOT / args.output
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(report)
        print(f"Wrote {output.relative_to(ROOT) if output.is_relative_to(ROOT) else output}")
    else:
        print(report, end="")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
